import { registerSW } from 'virtual:pwa-register';
import { logger } from '@/utils/logger';

/**
 * Unregisters every service worker on this origin and clears every Cache
 * Storage entry, then reloads. A service worker keeps running whatever code
 * it installed with until something replaces it — editing vite.config.ts's
 * workbox config does NOT retroactively fix a worker that already installed
 * the old, broken version. Call this from the DevTools console any time the
 * SW looks stale (errors referencing code you already removed, routes not
 * picking up config changes, etc). Exposed on `window` in dev only.
 */
async function hardResetServiceWorker(): Promise<void> {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator)) return;

  const registrations = await navigator.serviceWorker.getRegistrations();
  await Promise.all(registrations.map((r) => r.unregister()));

  if ('caches' in window) {
    const keys = await caches.keys();
    await Promise.all(keys.map((k) => caches.delete(k)));
  }

  logger.debug(`[PWA] Unregistered ${registrations.length} service worker(s) and cleared all caches. Reloading…`);
  window.location.reload();
}

/**
 * Registers the Workbox service worker generated by vite-plugin-pwa.
 * `autoUpdate` means a new SW takes over and reloads the page itself once
 * the new precache is ready — no user-facing "update available" prompt.
 * No-ops outside a browser (SSR/tests) and when the build has no SW (dev
 * without devOptions, or an environment where service workers are unsupported).
 */
export function registerServiceWorker(): void {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator)) return;

  if (import.meta.env.DEV) {
    // @ts-expect-error -- dev-only debug hook, intentionally not typed on Window
    window.__resetServiceWorker = hardResetServiceWorker;
    logger.debug('[PWA] Dev mode. If the SW looks stale/broken, run `__resetServiceWorker()` in this console.');
  }

  // registerSW() itself is synchronous setup — it can throw before any
  // callback fires (e.g. `virtual:pwa-register` resolving to a stub in an
  // unexpected environment), so guard the call too, not just its callbacks.
  try {
    registerSW({
      immediate: true,
      onRegisteredSW(swUrl, registration) {
        logger.debug('[PWA] Service worker registered:', swUrl);
        registration?.update().catch((err) => {
          logger.warn('[PWA] Background update check failed (offline?):', err);
        });
      },
      onRegisterError(error) {
        // Registration failing should never break the app shell — it just
        // means offline support / caching won't be available this session.
        logger.error('[PWA] Service worker registration failed:', error);
      },
      onOfflineReady() {
        logger.debug('[PWA] App is cached and ready to work offline.');
      },
    });
  } catch (error) {
    logger.error('[PWA] registerSW threw synchronously:', error);
  }
}
